const translations: Record<Locale, Record<string, string>> = {
  "zh-CN": {},
  en: {},
  ja: {},
  ko: {},
};
for (const [source, en, ja, ko] of entries) {
  translations.en[source] = en;
  translations.ja[source] = ja;
  translations.ko[source] = ko;
}

export function getLocale(): Locale {
  try {
    const value = localStorage.getItem("promptdock-ui-locale");
    if (value && locales.includes(value as Locale)) return value as Locale;
  } catch {
    // Keep the default locale when storage is unavailable.
  }
  return "zh-CN";
}

export function saveLocale(locale: Locale) {
  try {
    localStorage.setItem("promptdock-ui-locale", locale);
  } catch {
    // The current page can still use the selected locale for this session.
  }
}

export function t(source: string, locale = getLocale()) {
  return translations[locale][source] ?? source;
}
